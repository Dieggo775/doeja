-- ---------------------------------------------------------------
-- Usuários (3 perfis: USUARIO, CENTRO, ADMIN)
-- ---------------------------------------------------------------
CREATE TABLE usuarios (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(120) NOT NULL,
    email                 VARCHAR(160) NOT NULL,
    senha_hash            VARCHAR(100) NOT NULL,          -- nunca guardar senha pura (bcrypt)
    papel                 VARCHAR(20)  NOT NULL,
    ativo                 BOOLEAN      NOT NULL DEFAULT TRUE,
    lgpd_consentimento_em TIMESTAMPTZ,                    -- quando aceitou o termo (LGPD)
    criado_em             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuarios_papel CHECK (papel IN ('USUARIO', 'CENTRO', 'ADMIN'))
);

-- e-mail único sem diferenciar maiúsculas de minúsculas
CREATE UNIQUE INDEX ux_usuarios_email ON usuarios (lower(email));

-- ---------------------------------------------------------------
-- Centros de doação (igrejas, casas de acolhimento, pontos de arrecadação)
-- As colunas de nome até "ativo" correspondem à entidade CentroDoacao.
-- ---------------------------------------------------------------
CREATE TABLE centros_doacao (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(160)     NOT NULL,
    descricao             VARCHAR(500),
    endereco              VARCHAR(200),
    bairro                VARCHAR(100),
    cidade                VARCHAR(100),
    estado                VARCHAR(2),
    cep                   VARCHAR(9),
    latitude              DOUBLE PRECISION NOT NULL,
    longitude             DOUBLE PRECISION NOT NULL,
    telefone              VARCHAR(20)      NOT NULL,
    horario_funcionamento VARCHAR(200)     NOT NULL,
    ativo                 BOOLEAN          NOT NULL DEFAULT TRUE,

    -- novidades (ainda não usadas pela entidade)
    whatsapp              VARCHAR(20),                    -- só dígitos, com DDI: 5511999999999
    status                VARCHAR(20)      NOT NULL DEFAULT 'PENDENTE',
    responsavel_id        BIGINT REFERENCES usuarios (id) ON DELETE SET NULL,
    criado_em             TIMESTAMPTZ      NOT NULL DEFAULT now(),
    atualizado_em         TIMESTAMPTZ      NOT NULL DEFAULT now(),

    CONSTRAINT ck_centros_status CHECK (status IN ('PENDENTE', 'APROVADO', 'REJEITADO')),
    CONSTRAINT ck_centros_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_centros_longitude CHECK (longitude BETWEEN -180 AND 180)
);

CREATE INDEX ix_centros_status_ativo ON centros_doacao (status, ativo);
CREATE INDEX ix_centros_responsavel ON centros_doacao (responsavel_id);

-- ---------------------------------------------------------------
-- Categorias fixas de doação (alimentos, roupas, higiene...)
-- ---------------------------------------------------------------
CREATE TABLE categorias_doacao (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug  VARCHAR(40) NOT NULL UNIQUE,
    nome  VARCHAR(80) NOT NULL,
    ordem INTEGER     NOT NULL DEFAULT 0
);

-- ---------------------------------------------------------------
-- O que cada centro está precisando ou aceitando
-- ---------------------------------------------------------------
CREATE TABLE necessidades_centro (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    centro_id     BIGINT      NOT NULL REFERENCES centros_doacao (id) ON DELETE CASCADE,
    categoria_id  BIGINT      NOT NULL REFERENCES categorias_doacao (id),
    tipo          VARCHAR(10) NOT NULL DEFAULT 'PRECISA',
    descricao     VARCHAR(300),
    urgente       BOOLEAN     NOT NULL DEFAULT FALSE,
    ativa         BOOLEAN     NOT NULL DEFAULT TRUE,
    atualizada_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ux_necessidade_centro_categoria UNIQUE (centro_id, categoria_id),
    CONSTRAINT ck_necessidade_tipo CHECK (tipo IN ('PRECISA', 'ACEITA'))
);

-- ---------------------------------------------------------------
-- Doações registradas pelos usuários
-- Privacidade: o usuário só vê as próprias; o centro só vê as recebidas.
-- (essa regra é aplicada na API; aqui ficam os vínculos)
-- ---------------------------------------------------------------
CREATE TABLE doacoes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT      NOT NULL REFERENCES usuarios (id),
    centro_id     BIGINT      NOT NULL REFERENCES centros_doacao (id),
    status        VARCHAR(20) NOT NULL DEFAULT 'PROMETIDA',
    observacao    VARCHAR(500),
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_doacoes_status CHECK (status IN ('PROMETIDA', 'ENTREGUE', 'CONFIRMADA', 'CANCELADA'))
);

CREATE INDEX ix_doacoes_usuario ON doacoes (usuario_id);
CREATE INDEX ix_doacoes_centro ON doacoes (centro_id);

CREATE TABLE itens_doacao (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doacao_id    BIGINT       NOT NULL REFERENCES doacoes (id) ON DELETE CASCADE,
    categoria_id BIGINT       NOT NULL REFERENCES categorias_doacao (id),
    descricao    VARCHAR(200) NOT NULL,
    quantidade   INTEGER      NOT NULL DEFAULT 1,
    CONSTRAINT ck_itens_quantidade CHECK (quantidade > 0)
);

CREATE INDEX ix_itens_doacao_doacao ON itens_doacao (doacao_id);
